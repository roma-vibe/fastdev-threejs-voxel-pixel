const COLOR_KEYS = new Set([
  'sunColor',
  'hemiSky',
  'hemiGround',
  'skyTop',
  'skyHorizon',
  'skyBottom',
  'glowColor',
  'auroraColor',
  'fogColor',
  'cloudColor',
]);

export function lerpPreset(a, b, t) {
  const out = {};
  for (const k of Object.keys(b)) {
    const va = a[k],
      vb = b[k];
    if (typeof vb === 'number' && typeof va === 'number') {
      if (COLOR_KEYS.has(k)) out[k] = lerpColor(va, vb, t);
      else out[k] = va + (vb - va) * t;
    } else if (Array.isArray(vb) && Array.isArray(va))
      out[k] = vb.map((v, i) => va[i] + (v - va[i]) * t);
    else out[k] = t < 0.5 ? (va ?? vb) : vb;
  }
  return out;
}

function lerpColor(a, b, t) {
  const ar = (a >> 16) & 255,
    ag = (a >> 8) & 255,
    ab = a & 255;
  const br = (b >> 16) & 255,
    bg = (b >> 8) & 255,
    bb = b & 255;
  return (
    (Math.round(ar + (br - ar) * t) << 16) |
    (Math.round(ag + (bg - ag) * t) << 8) |
    Math.round(ab + (bb - ab) * t)
  );
}
